// Run:  npx tsx src/utils/vehicleIdOcr.selftest.ts      (from the mobile folder; nothing imports this file, the app never bundles it)
import { extractVehicleIds, type OcrLike } from './vehicleIdOcr'

const lines = (...l: string[]): OcrLike => ({ text: l.join('\n'), blocks: [{ text: l.join('\n'), lines: l.map((text) => ({ text })) }] })
let failed = 0
const check = (name: string, ok: boolean, detail: unknown) => { if (!ok) failed++; console.log((ok ? 'PASS ' : 'FAIL ') + name + (ok ? '' : '  -> ' + JSON.stringify(detail))) }
const top = (o: OcrLike) => extractVehicleIds(o)[0]

let c = top(lines('P6DEC12CPDG015344'))
check('chassis, clean', c?.value === 'P6DEC12CPDG015344' && c.kind === 'chassis' && !c.corrected, c)
c = top(lines('CHASSIS NO: P6DEC 12CPDG-015344', 'MADE IN INDIA', 'BGAUSS AUTO'))
check('chassis among other words, spaces and a hyphen', c?.value === 'P6DEC12CPDG015344' && c.kind === 'chassis', c)
c = top(lines('p6dec12cpdg015344'))
check('chassis, lower case', c?.value === 'P6DEC12CPDG015344', c)
c = top(lines('P6DEC12CPDGO15344'))
check('chassis, letter O read for 0 is corrected', c?.value === 'P6DEC12CPDG015344' && c.corrected, c)
c = top(lines('P6DEC12CPDG0I5344'))
check('chassis, letter I read for 1 is corrected', c?.value === 'P6DEC12CPDG015344' && c.corrected, c)
c = top(lines('P6DEC12C', 'PDG015344'))
check('chassis split over two lines', c?.value === 'P6DEC12CPDG015344', c)
c = top(lines('MH 05 AB 1234'))
check('registration with spaces', c?.value === 'MH05AB1234' && c.kind === 'reg', c)
c = top(lines('MH05A81234'))
check('registration, 8 read for B is corrected', c?.value === 'MH05AB1234' && c.corrected, c)
c = top(lines('DL 3C AB 1234'))
check('registration Delhi style (1-digit district, 3 letters)', c?.value === 'DL3CAB1234', c)
c = top(lines('MH05', 'AB1234'))
check('registration on two plate rows', c?.value === 'MH05AB1234', c)
c = top(lines('22 BH 1234 AA'))
check('Bharat series', c?.value === '22BH1234AA' && c.kind === 'reg', c)
check('no number on the photo -> nothing', extractVehicleIds(lines('BGAUSS ELECTRIC SCOOTER', 'MADE IN INDIA', 'MAX SPEED')).length === 0, extractVehicleIds(lines('BGAUSS ELECTRIC SCOOTER')))
check('long word without digits is not a chassis', extractVehicleIds(lines('ELECTRICSCOOTERSBGAUSS')).length === 0, extractVehicleIds(lines('ELECTRICSCOOTERSBGAUSS')))
const weak = extractVehicleIds(lines('P6DEC12CPDG01534'))
check('16 characters read -> only a weak guess, flagged loose', weak.length > 0 && weak.every((x) => x.loose), weak)
const both = extractVehicleIds(lines('P6DEC12CPDG015344', 'MH 05 AB 1234'))
check('both on one photo: both offered, chassis not split into a fake registration', both.some((x) => x.value === 'P6DEC12CPDG015344') && both.some((x) => x.value === 'MH05AB1234') && both.every((x) => x.value.length === 17 || x.value === 'MH05AB1234'), both)
c = top(lines('MH05AB1234'))
check('registration, clean (not cut short or mis-read)', c?.value === 'MH05AB1234' && !c.corrected, c)
c = top(lines('TN 09 AB 1234'))
check('registration Tamil Nadu', c?.value === 'TN09AB1234', c)
c = top(lines('KA 01 A 1234'))
check('registration with a single series letter', c?.value === 'KA01A1234', c)
c = top(lines('IND', 'MH 05 AB 1234'))
check('registration next to the IND mark', c?.value === 'MH05AB1234', c)
check('plain words with many O and I are not a chassis', extractVehicleIds(lines('CONTROLLER MODULE INDIA ORIGIN')).length === 0, extractVehicleIds(lines('CONTROLLER MODULE INDIA ORIGIN')))
if (failed > 0) throw new Error(failed + ' self-test(s) failed')
console.log('All self-tests passed.')